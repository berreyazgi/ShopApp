/**
 * Creates an SVG icon element.
 *
 * @param {keyof typeof icons} name  - Icon identifier
 * @param {{ size?: number, label?: string, className?: string }} [options]
 * @returns {SVGElement|HTMLSpanElement}
 */
export function createIcon(name, options = {}) {
  const { size = 20, label, className = '' } = options;
  const svgStr = icons[name];

  if (!svgStr) {
    console.warn(`[Icon] Unknown icon: "${name}"`);
    const fallback = document.createElement('span');
    fallback.textContent = '?';
    return fallback;
  }

  const wrapper = document.createElement('span');
  wrapper.className = `icon icon--${name}${className ? ` ${className}` : ''}`;
  wrapper.setAttribute('aria-hidden', label ? 'false' : 'true');
  if (label) wrapper.setAttribute('aria-label', label);
  wrapper.style.cssText = `display:inline-flex;align-items:center;justify-content:center;width:${size}px;height:${size}px;flex-shrink:0;`;
  wrapper.innerHTML = svgStr;

  const svg = wrapper.querySelector('svg');
  if (svg) {
    svg.setAttribute('width',  size);
    svg.setAttribute('height', size);
    svg.style.width  = `${size}px`;
    svg.style.height = `${size}px`;
  }

  return wrapper;
}

/** Returns the raw SVG string for a given icon name. */
export function getIconSvg(name) {
  return icons[name] ?? '';
}
